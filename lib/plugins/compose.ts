import {atomicWriteFile} from "@/lib/atomic-file";
import {readPluginConfigForBackend} from "@/lib/plugins/config";
import {findDiscoveredPlugin} from "@/lib/plugins/discovery";
import {generatedComposeFile, pluginDataDir, pluginRuntimeEnvFile} from "@/lib/plugins/paths";
import {pluginServiceName} from "@/lib/plugins/ids";
import {listRegistryRecords, pluginIsActive} from "@/lib/plugins/registry";
import {readPluginToken} from "@/lib/plugins/tokens";
import type {DiscoveredPlugin} from "@/lib/plugins/types";

function yamlQuote(value: string): string {
    return JSON.stringify(value);
}

function serviceBlock(plugin: DiscoveredPlugin, token: string): string {
    const service = pluginServiceName(plugin.manifest.id);
    const runtime = plugin.manifest.runtime;
    const folder = plugin.folderName;
    const env: Record<string, string> = {
        GROWCAST_URL: "http://growcast:3000",
        GROWCAST_PLUGIN_ID: plugin.manifest.id,
        GROWCAST_PLUGIN_TOKEN: token,
        PYTHONDONTWRITEBYTECODE: "1",
        ...(runtime?.extraEnv ?? {}),
    };
    const header: string[] = [`  ${service}:`];
    if (runtime?.type === "docker" || runtime?.dockerfile || runtime?.image) {
        if (runtime.image) {
            header.push(`    image: ${yamlQuote(runtime.image)}`);
        } else {
            header.push("    build:");
            header.push(`      context: ./plugins/${folder}`);
            header.push(`      dockerfile: ${runtime.dockerfile ?? "Dockerfile"}`);
        }
    } else if (runtime?.type === "python") {
        header.push("    image: python:3.12-slim");
    } else if (runtime?.type === "node") {
        header.push("    image: node:24-alpine");
    }
    header.push("    restart: unless-stopped");
    header.push('    user: "1001:1001"');
    header.push("    environment:");
    for (const [key, value] of Object.entries(env)) {
        header.push(`      ${key}: ${yamlQuote(value)}`);
    }
    header.push("    env_file:");
    // Host-relative: compose runs on the project root, not inside the GrowCast container.
    header.push(`      - ${yamlQuote(`./data/plugins/${plugin.manifest.id}/runtime.env`)}`);
    header.push("    volumes:");
    header.push(`      - ./plugins/${folder}:/plugin:ro`);
    header.push(`      - ./data/plugins/${plugin.manifest.id}:/data`);
    for (const volume of runtime?.extraVolumes ?? []) {
        header.push(`      - ${yamlQuote(volume)}`);
    }
    header.push("    depends_on: [growcast]");
    if (runtime?.type === "python") {
        header.push("    working_dir: /plugin");
        header.push(`    command: ["python", "-u", ${yamlQuote(runtime.entry ?? "backend/main.py")}]`);
    } else if (runtime?.type === "node") {
        header.push("    working_dir: /plugin");
        header.push(`    command: ["node", ${yamlQuote(runtime.entry ?? "backend/main.js")}]`);
    }
    if (runtime?.command && runtime.command.length > 0) {
        header.push(`    command: [${runtime.command.map((item) => yamlQuote(item)).join(", ")}]`);
    }
    if (runtime?.shmSize) {
        header.push(`    shm_size: ${yamlQuote(runtime.shmSize)}`);
    }
    return `${header.join("\n")}\n`;
}

export async function writeRuntimeEnv(pluginId: string): Promise<void> {
    const token = await readPluginToken(pluginId);
    const config = await readPluginConfigForBackend(pluginId);
    const lines = [
        `GROWCAST_PLUGIN_ID=${pluginId}`,
        token ? `GROWCAST_PLUGIN_TOKEN=${token}` : "",
        `GROWCAST_URL=http://growcast:3000`,
    ];
    for (const [key, value] of Object.entries(config)) {
        const envKey = key.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
        lines.push(`${envKey}=${value}`);
    }
    await atomicWriteFile(pluginRuntimeEnvFile(pluginId), `${lines.filter(Boolean).join("\n")}\n`, 0o600);
}

export async function generatePluginsCompose(): Promise<string> {
    const records = await listRegistryRecords();
    const services: string[] = [];
    for (const record of records) {
        if (!pluginIsActive(record) && record.status !== "enabled") {
            continue;
        }
        if (!record.hashMatches) {
            continue;
        }
        const discovered = await findDiscoveredPlugin(record.id);
        if (!discovered?.manifest.runtime || discovered.manifest.runtime.type === "none") {
            continue;
        }
        const token = await readPluginToken(record.id);
        if (!token) {
            continue;
        }
        await writeRuntimeEnv(record.id);
        services.push(serviceBlock(discovered, token));
    }
    const yaml = services.length > 0
        ? `# Generated by GrowCast. Do not edit.\n# Enable or disable plugins in Admin → Plugins.\nservices:\n${services.join("\n")}\n`
        : "# Generated by GrowCast. Do not edit.\n# Enable or disable plugins in Admin → Plugins.\nservices: {}\n";
    await atomicWriteFile(generatedComposeFile(), yaml);
    return yaml;
}

export function pluginDataHostPath(pluginId: string): string {
    return pluginDataDir(pluginId);
}
